import type { CharacterId } from './characters';

export interface SkillDefinition {
  id: number;
  name: string;
  category: string;
  description: string;
  effect: string;
  values: readonly number[]; // Lv.1~5 최종값, 단위는 effect에 명시
  secondary?: readonly number[]; // 복합 효과의 두 번째 최종값, 단위는 effect에 명시
}
function skill(id: number, name: string, description: string, effect: string, values: number[], secondary?: number[]): SkillDefinition {
  return { id, name, description, effect, values, secondary,
    category: id >= 21 ? '치명타' : id <= 6 ? '전용 무기' : id <= 10 ? '자동 공격' : id <= 15 ? '고유 운용' : '생존과 수집' };
}

